/**
 * 岗位描述（JD）：增删改、关键词解析，以及"从这份 JD 生成岗位简历"的入口。
 *
 * <h2>JD 是简历的绑定对象</h2>
 * 岗位简历在创建时就绑定一份 JD；详情页的<b>规则覆盖度只使用该绑定的 JD</b>。
 * 通用简历不显示 JD 覆盖评分入口 —— 没有目标岗位就没有"覆盖率"这回事。
 *
 * <h2>解析是确定性的，不是 AI</h2>
 * {@code JdKeywordParser} 按规则版本（{@code JdParserRuleVersion}）抽取关键词，
 * 结果可复现、可回归；AI 只在后续的选材与生成阶段介入。
 * <b>不要把解析改成模型调用</b>：那会让同一份 JD 每次抽出不同关键词，覆盖度分数失去可比性。
 *
 * <h2>不可变快照</h2>
 * 进入选材/生成流程时，JD 内容会被冻结进任务快照，防止生成期间被编辑的数据混入。
 */
